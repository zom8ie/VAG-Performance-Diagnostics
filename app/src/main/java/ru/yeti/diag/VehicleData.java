    static double lambdaPowerKw(double gramsPerSecond,double lambda){
        if(!Double.isFinite(gramsPerSecond)||gramsPerSecond<0||!Double.isFinite(lambda)||lambda<=0)return Double.NaN;
        return gramsPerSecond*3600/(STOICHIOMETRIC_AFR*lambda*SPECIFIC_FUEL_CONSUMPTION);
    }
