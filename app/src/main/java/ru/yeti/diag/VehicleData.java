    static int requiredFields(String mode,int group){
        if(mode.equals("ECM")||mode.equals("ENGINE")){
            switch(group){
                case 3:return 0b0010;
                case 115: return 0b1100;
                case 114: return 0b1000;
                case 14:return 0b0100;
                case 16:return 0b0001;
                case 15:return 0b0111;
                case 20:return 0b1111;
                case 31:return 0b0001;
                case 32:return 0b0011;
                case 91:return 0b1100;
                case 93:return 0b0100;
                case 106:return 0b0011;
            }
        }
        if(mode.equals("DSG")){
            if(group==11||group==12||group==16)return 0b1111;
            if(group==19)return 0b0111;
            if(group==20)return 0b0011;
        }
        if(mode.equals("ABS")){
            if(group==1)return 0b1111;
            if(group==4)return 0b0011;
            if(group==5)return 0b0001;
            if(group==6)return 0b0001;
        }
        return 0;
    }

    static Protocol.Reading reading(String mode,int group,int index,int type,int a,int b){
        if(mode.equals("DSG")&&(group==11||group==12)){
            if(index==2&&type==0x18)return new Protocol.Reading(a*b/1000.0,"А");
        }
        if(mode.equals("DSG")&&group==16&&type==0x0D)
            return new Protocol.Reading(a*(b-127)/1000.0,"мм");
        return Protocol.kwpValue(type,a,b);
    }
