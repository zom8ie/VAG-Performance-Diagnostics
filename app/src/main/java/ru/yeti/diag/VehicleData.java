    private static void group(Map<Integer,Field[]> catalog,int id,String... specs){
        Field[] fields=new Field[4];
        for(int i=0;i<fields.length;i++){
            String spec=i<specs.length?specs[i]:null;
            if(spec==null)continue;
            String[] parts=spec.split("\\|",3);
            String name=parts[0], description=parts.length==3?parts[2]:"";
            java.util.regex.Matcher codes=java.util.regex.Pattern.compile("\\b(?:[GNVFJ]\\d{1,3}|F)\\b").matcher(name+" "+description);
            List<String> symbols=new ArrayList<>();
            while(codes.find()&&!symbols.contains(codes.group()))symbols.add(codes.group());
            if(!symbols.isEmpty()&&!name.matches(".*\\b(?:"+String.join("|",symbols)+")\\b.*"))name+=" ("+String.join(", ",symbols)+")";
            if(!symbols.isEmpty()&&description.isEmpty())description="Обозначение компонента: "+String.join(", ",symbols)+".";
            description=measurementDescription(name,description);
            fields[i]=new Field(name,parts.length>=2?parts[1]:"",description);
        }
        catalog.put(id,fields);
    }

